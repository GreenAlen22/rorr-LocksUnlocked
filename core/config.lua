-- Все числа мода. Единственный источник: остальные модули читают отсюда и
-- своих констант баланса не держат.

LU = LU or {}

local C = {}

-- Сундуки, которые можно взломать. Массив, а не таблица по
-- имени: порядок обхода pairs в Lua 5.4 меняется от запуска к запуску.
--   base    — начальная цена, третий аргумент interactable_init_cost в Create;
--   diff    — сложность 1..4 по цене: 25–30, 50–60, 100, 500;
--   upgrade — индекс весов item_drop для тира выше (scr_treasureWeights.gml:
--             0 малый, 1 большой, 2 золотой, 4..9 категорийные малый/большой).
C.CHESTS = {
    { obj = "oChest1",          base = 25,  diff = 1, upgrade = 1 },
    { obj = "oChestDamage1",    base = 30,  diff = 1, upgrade = 5 },
    { obj = "oChestHealing1",   base = 30,  diff = 1, upgrade = 7 },
    { obj = "oChestUtility1",   base = 30,  diff = 1, upgrade = 9 },
    { obj = "oBarrelEquipment", base = 25,  diff = 1 },
    { obj = "oChest2",          base = 50,  diff = 2, upgrade = 2 },
    { obj = "oChest4",          base = 55,  diff = 2 },
    { obj = "oChestDamage2",    base = 60,  diff = 2, upgrade = 2 },
    { obj = "oChestHealing2",   base = 60,  diff = 2, upgrade = 2 },
    { obj = "oChestUtility2",   base = 60,  diff = 2, upgrade = 2 },
    { obj = "oGunchest",        base = 100, diff = 3 },
    { obj = "oChest5",          base = 500, diff = 4 },
}

-- Перепрошивка Робомандо: мини-игра вместо
-- мгновенного открытия, замок на столько уровней проще, без шума, цены и
-- потери золота. Скипетр сохраняет свой шанс двойного
-- (scr_ror_init_survivor_robomando.gml:266).
C.REWIRE_DIFF_DOWN      = 1
C.REWIRE_SCEPTER_DOUBLE = 0.25

-- Прочее платное, что взламывает только Перепрошивка (дроны, терминалы):
-- сложность по базовой цене. До 35 — 1, до 75 — 2, до 150 — 3, дороже — 4,
-- те же ступени, что у сундуков (25–30, 50–60, 100, 500).
C.EXTRA_DIFF_COST = { 35, 75, 150 }

-- Награда
-- Тир выше за чистый взлом, по сложностям 1..4. Большой сундук поднимается
-- на веса золотого — это всегда красный предмет, поэтому его шанс ниже:
-- с 0.08 красный из большого выходит ~27% против ванильных 21%. Где тира
-- выше нет, этот шанс уходит в двойной.
C.UPGRADE_CHANCE = { 0.20, 0.08, 0.08, 0.08 }
C.STREAK_STEP    = 0.05   -- шанс двойного за единицу серии
C.DOUBLE_CAP     = 0.30   -- потолок шанса двойного от серии

-- Провал и ошибки
C.MAX_MISTAKES     = 3
C.GOLD_LOSS        = 0.15 -- доля текущего золота, которую забирает провал
C.MARKUP_START     = 0.5  -- процент наценки провала в начале забега
C.MARKUP_STEP      = 0.1  -- прибавка процента...
C.MARKUP_EVERY_MIN = 3    -- ...за каждые столько минут забега
C.MARKUP_MAX       = 1.5

-- Лимит времени и шум по сложностям 1..4
C.TIME_LIMIT   = { 20, 25, 30, 40 }        -- секунды
C.NOISE_RADIUS = { 200, 300, 400, 600 }    -- пиксели мира
C.NOISE_SEC    = 1.5                       -- сколько невидимость спадает

-- Расстояния, пиксели мира
C.PICK_RADIUS = 16   -- как у взлома Robomando (_survivor_robomando_hack_find_target)
C.CANCEL_DIST = 48   -- дальше — взлом прерван

-- Сеть, кадры
C.HEARTBEAT     = 60    -- взломщик отчитывается не реже
C.WATCHDOG      = 300   -- хост освобождает замок после такого молчания
C.GRANT_TIMEOUT = 120   -- просивший сдаётся, если хост молчит

C.RESULT_SEC = 1.0      -- сколько панель показывает итог

LU.Config = C
